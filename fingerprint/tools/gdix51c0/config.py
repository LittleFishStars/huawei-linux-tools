#: DAC 在配置块里的字节偏移（配置数据从 payload[3] 开始，函数内部按绝对偏移处理）
OFF_DAC_MAIN = 122
OFF_DAC_1 = 126
OFF_DAC_2 = 130
OFF_DAC_3 = 134
#: 读出时序寄存器
OFF_REG_0082 = 178
OFF_REG_005C = 118

REG_0082_DEFAULT = 0x1D80
REG_005C_DEFAULT = 0x0110
LEGACY_DAC_MAIN = 0x0B38


class ConfigError(ValueError):
    pass


def config_checksum(config: bytes) -> int:
    """块内 16 位校验和。"""
    if len(config) < 4 or len(config) % 2:
        raise ConfigError(f"配置块长度非法: {len(config)}")
    total = 0xA5A5
    for off in range(0, len(config) - 2, 2):
        total += config[off] | (config[off + 1] << 8)
    return (-total) & 0xFFFF


def update_checksum(config: bytearray) -> None:
    """把校验和写回末尾两字节。"""
    csum = config_checksum(bytes(config))
    config[-2] = csum & 0xFF
    config[-1] = (csum >> 8) & 0xFF


def checksum_valid(config: bytes) -> bool:
    stored = config[-2] | (config[-1] << 8)
    return stored == config_checksum(config)


def build(
    dac_main: int = LEGACY_DAC_MAIN,
    dac_1: int = 0xB5,
    dac_2: int = 0xB3,
    dac_3: int = 0xB3,
    reg_0082: int = REG_0082_DEFAULT,
    reg_005c: int = REG_005C_DEFAULT,
    patch_timing: bool | None = None,
) -> bytes:
    """按本机 DAC 生成配置块（含外框命令头与末尾校验和）。

    ``patch_timing`` 为 None 时随 DAC 决定：只有 DAC 高于 legacy 0x0b38 才改
    读出时序，因为旧时序配新偏置会让读出无法完成。
    """
    cfg = bytearray(DEFAULT_CFG)
    if len(cfg) != 232:
        raise ConfigError(f"模板长度异常: {len(cfg)}")

    cfg[OFF_DAC_MAIN] = dac_main & 0xFF
    cfg[OFF_DAC_MAIN + 1] = (dac_main >> 8) & 0xFF
    cfg[OFF_DAC_1] = dac_1 & 0xFF
    cfg[OFF_DAC_2] = dac_2 & 0xFF
    cfg[OFF_DAC_3] = dac_3 & 0xFF

    if patch_timing is None:
        patch_timing = dac_main != LEGACY_DAC_MAIN
    if patch_timing:
        cfg[OFF_REG_005C] = reg_005c & 0xFF
        cfg[OFF_REG_005C + 1] = (reg_005c >> 8) & 0xFF
        cfg[OFF_REG_0082] = reg_0082 & 0xFF
        cfg[OFF_REG_0082 + 1] = (reg_0082 >> 8) & 0xFF

    # 内层校验和作用于 config[3:228]，其中末两字节就是校验和自身位置
    inner = bytearray(cfg[3 : len(cfg) - 1])
    update_checksum(inner)
    cfg[len(cfg) - 3] = inner[-2]
    cfg[len(cfg) - 2] = inner[-1]

    # 最后的 0x?? 是外层载荷校验和（覆盖 payload 前 231 字节）
    from . import wire

    cfg[len(cfg) - 1] = wire.checksum(bytes(cfg[: len(cfg) - 1]))
    return bytes(cfg)


def selftest() -> None:
    """模板自身的校验和必须自洽。"""
    cfg = bytearray(DEFAULT_CFG)
    inner = bytearray(cfg[3 : len(cfg) - 1])
    update_checksum(inner)
    cfg[len(cfg) - 3] = inner[-2]
    cfg[len(cfg) - 2] = inner[-1]
    if not checksum_valid(bytes(cfg[3 : len(cfg) - 1])):
        raise AssertionError("模板内层校验和不自洽")
